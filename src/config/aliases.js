// Товчлолыг бүлэгт нь олох → { canonical, aliases } эсвэл null
export function findAliasGroup(tovch) {
  const t = String(tovch || '').trim().toLowerCase();
  if (!t) return null;
  for (const [canonical, aliases] of Object.entries(ALIAS_GROUPS)) {
    if (canonical === t || aliases.includes(t)) return { canonical, aliases };
  }
  return null;
}
